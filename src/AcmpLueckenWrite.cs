    // Parameter aus einem gesicherten Wert (Typname aus GetDataTypeName bzw. aus dem Plan)
    public static SqlParameter ParFor(string name, string type, JToken v)
    {
        var p = new SqlParameter(); p.ParameterName = name;
        type = (type ?? "nvarchar").ToLowerInvariant();
        bool nul = v == null || v.Type == JTokenType.Null;
        if (IsBinaryType(type)) { p.SqlDbType = SqlDbType.VarBinary; p.Size = -1; p.Value = nul ? (object)DBNull.Value : BytesOfHex((string)v); return p; }
        switch (type)
        {
            case "uniqueidentifier": p.SqlDbType = SqlDbType.UniqueIdentifier; p.Value = nul ? (object)DBNull.Value : new Guid(((string)v).Trim('{', '}')); break;
            case "xml": p.SqlDbType = SqlDbType.Xml; p.Value = nul ? (object)DBNull.Value : (string)v; break;
            case "sql_variant": p.SqlDbType = SqlDbType.Variant; p.Value = nul ? (object)DBNull.Value : VariantOf((JObject)v); break;
            case "datetime": case "datetime2": case "smalldatetime": case "date":
                p.SqlDbType = SqlDbType.DateTime2; p.Value = nul ? (object)DBNull.Value : DateTime.Parse((string)v, CultureInfo.InvariantCulture, DateTimeStyles.RoundtripKind); break;
            case "bit": p.SqlDbType = SqlDbType.Bit; p.Value = nul ? (object)DBNull.Value : (bool)v; break;
            case "tinyint": p.SqlDbType = SqlDbType.TinyInt; p.Value = nul ? (object)DBNull.Value : (byte)(long)v; break;
            case "smallint": p.SqlDbType = SqlDbType.SmallInt; p.Value = nul ? (object)DBNull.Value : (short)(long)v; break;
            case "int": p.SqlDbType = SqlDbType.Int; p.Value = nul ? (object)DBNull.Value : (int)(long)v; break;
            case "bigint": p.SqlDbType = SqlDbType.BigInt; p.Value = nul ? (object)DBNull.Value : (long)v; break;
            case "float": p.SqlDbType = SqlDbType.Float; p.Value = nul ? (object)DBNull.Value : (double)v; break;
            case "real": p.SqlDbType = SqlDbType.Real; p.Value = nul ? (object)DBNull.Value : (float)(double)v; break;
            case "decimal": case "numeric": case "money":
                p.SqlDbType = SqlDbType.Decimal; p.Value = nul ? (object)DBNull.Value : decimal.Parse((string)v, CultureInfo.InvariantCulture); break;
            case "varchar": case "char": case "text": p.SqlDbType = SqlDbType.VarChar; p.Size = -1; p.Value = nul ? (object)DBNull.Value : (string)v; break;
            default: p.SqlDbType = SqlDbType.NVarChar; p.Size = -1; p.Value = nul ? (object)DBNull.Value : (string)v; break;
        }
        return p;
    }

    // Schluessel einer Zeile; fehlt eine Schluesselspalte, ist der Stand unbrauchbar (Review 25.10.2026: sonst fielen alle Zeilen zusammen)
    static string KeyOf(JObject row, JArray key)
    {
        var l = new List<string>();
        foreach (JToken k in key)
        {
            JToken v = row[(string)k];
            if (v == null) throw new Exception("Interner Fehler: Schluesselspalte " + k + " fehlt im gesicherten Stand.");
            l.Add(v.ToString(Newtonsoft.Json.Formatting.None).ToUpperInvariant());
        }
        return string.Join("|", l.ToArray());
    }

    static Dictionary<string, JObject> RowsByKey(JObject snap)
    {
        var d = new Dictionary<string, JObject>(StringComparer.Ordinal);
        foreach (JObject r in (JArray)snap["rows"])
        {
            string k = KeyOf(r, (JArray)snap["k"]);
            if (d.ContainsKey(k)) throw new Exception("Interner Fehler: Schluessel " + k + " in " + snap["t"] + " doppelt - Schluessel der Sicherung pruefen.");
            d[k] = r;
        }
        return d;
    }

    static string Canon(JObject row) { return row.ToString(Newtonsoft.Json.Formatting.None); }

    // Weicht der jetzige Stand einer Tabelle vom erwarteten ab? null = nein, sonst Beschreibung
    public static string Drift(JObject now, JObject expected)
    {
        Dictionary<string, JObject> a = RowsByKey(now), b = RowsByKey(expected);
        int changed = 0, added = 0, gone = 0;
        foreach (var kv in b) { JObject x; if (!a.TryGetValue(kv.Key, out x)) gone++; else if (Canon(x) != Canon(kv.Value)) changed++; }
        foreach (var kv in a) if (!b.ContainsKey(kv.Key)) added++;
        if (changed + added + gone == 0) return null;
        var l = new List<string>();
        if (changed > 0) l.Add(changed + " geaendert");
        if (added > 0) l.Add(added + " dazugekommen");
        if (gone > 0) l.Add(gone + " fehlen");
        return (string)expected["t"] + ": " + string.Join(", ", l.ToArray());
    }

    // Was die Ruecknahme je Tabelle tut: Zeilen wieder anlegen (nur vorher), entfernen (nur nachher), aendern (beide, verschieden)
    public static void DiffCounts(JObject before, JObject after, out int insert, out int delete, out int update)
    {
        Dictionary<string, JObject> b = RowsByKey(before), a = RowsByKey(after);
        insert = 0; delete = 0; update = 0;
        foreach (var kv in b) { JObject x; if (!a.TryGetValue(kv.Key, out x)) insert++; else if (Canon(x) != Canon(kv.Value)) update++; }
        foreach (var kv in a) if (!b.ContainsKey(kv.Key)) delete++;
    }

