    void CcFolderChain(SqlConnection c, string folderId, out string path, out bool aagon)
    {
        path = ""; aagon = false;
        if (string.IsNullOrEmpty(folderId)) return;
        var q = Cmd(c, "WITH f AS (SELECT ScriptStructureID, ParentID, Description, StrucLevel, 0 AS d FROM SYS_SCRIPT_STRUCTURE WHERE ScriptStructureID = @f " +
            "UNION ALL SELECT p.ScriptStructureID, p.ParentID, p.Description, p.StrucLevel, f.d + 1 FROM SYS_SCRIPT_STRUCTURE p JOIN f ON p.ScriptStructureID = f.ParentID WHERE f.d < 30) " +
            "SELECT Description, StrucLevel FROM f ORDER BY d DESC");
        q.Parameters.AddWithValue("@f", folderId);
        var parts = new List<string>();
