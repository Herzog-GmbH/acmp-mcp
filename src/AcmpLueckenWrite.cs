        if (spec["c"] != null)
        {
            var l = new List<string>(); foreach (JToken x in (JArray)spec["c"]) l.Add("[" + ((string)x).Replace("]", "") + "]");
            cols = string.Join(", ", l.ToArray());
        }
        var q = c.CreateCommand(); q.Transaction = tx; q.CommandTimeout = SqlTimeout;
        q.CommandText = "SELECT " + cols + " FROM dbo.[" + t + "] WHERE " + (string)spec["w"];
        var res = new JObject(); res["t"] = t; res["k"] = spec["k"];
        var types = new JObject(); var rows = new JArray();
        using (var r = q.ExecuteReader())
        {
            for (int i = 0; i < r.FieldCount; i++) types[r.GetName(i)] = r.GetDataTypeName(i).ToLowerInvariant();
            foreach (JToken k in (JArray)spec["k"]) if (types[(string)k] == null) throw new Exception("Interner Fehler: Schluesselspalte " + k + " gibt es in " + t + " nicht.");
            while (r.Read())
            {
                var o = new JObject();
                for (int i = 0; i < r.FieldCount; i++) o[r.GetName(i)] = CellOf(r.GetValue(i), (string)types[r.GetName(i)]);
                rows.Add(o);
            }
        }
        res["types"] = types; res["rows"] = rows;
        return res;
    }

