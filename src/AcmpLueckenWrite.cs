    // Wert einer DB-Zelle fuer die Sicherung: Binaer als 0x-Hex, GUID als D gross, Zeit ISO, sql_variant mit CLR-Typ
    static JToken DbValue(object v)
    {
        if (v == null || v is DBNull) return JValue.CreateNull();
        if (v is byte[]) return HexOf((byte[])v);
        if (v is Guid) return ((Guid)v).ToString("D").ToUpperInvariant();
        if (v is DateTime) return ((DateTime)v).ToString("o", CultureInfo.InvariantCulture);
        if (v is double || v is float) return Convert.ToDouble(v, CultureInfo.InvariantCulture);
        if (v is decimal) return ((decimal)v).ToString(CultureInfo.InvariantCulture);
        if (v is bool) return (bool)v;
        if (v is byte || v is short || v is int || v is long) return Convert.ToInt64(v, CultureInfo.InvariantCulture);
        return Convert.ToString(v, CultureInfo.InvariantCulture);
    }

    static JToken CellOf(object v, string type)
    {
        if (type == "sql_variant" && v != null && !(v is DBNull))
        {
            var o = new JObject(); o["clr"] = v.GetType().Name; o["v"] = DbValue(v); return o;
        }
        return DbValue(v);
    }

    static object VariantOf(JObject o)
    {
        string clr = (string)o["clr"]; JToken v = o["v"];
        if (v == null || v.Type == JTokenType.Null) return DBNull.Value;
        switch (clr)
        {
            case "Int32": return (int)(long)v;
            case "Int16": return (short)(long)v;
            case "Byte": return (byte)(long)v;
            case "Int64": return (long)v;
            case "Boolean": return (bool)v;
            case "Double": return (double)v;
            case "Single": return (float)(double)v;
            case "Decimal": return decimal.Parse((string)v, CultureInfo.InvariantCulture);
            case "DateTime": return DateTime.Parse((string)v, CultureInfo.InvariantCulture, DateTimeStyles.RoundtripKind);
            case "Guid": return new Guid((string)v);
            case "Byte[]": return BytesOfHex((string)v);
        }
        return (string)v;
    }

