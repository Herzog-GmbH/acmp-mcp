    // ---------- Wartungsfenster ----------
    List<MwWindow> WindowsArg(JObject a)
    {
        var ws = new List<MwWindow>();
        JToken t = a["windows"];
        if (t != null && t.Type == JTokenType.String) { string s = ((string)t).Trim(); if (s.StartsWith("[")) t = JToken.Parse(s); }
        if (t != null && t.Type == JTokenType.Array)
        {
            foreach (JToken x in (JArray)t)
            {
                JObject o = x as JObject;
                if (o == null) throw new Exception("windows: jedes Fenster als Objekt {days, start, end, label}.");
                var w = new MwWindow();
                JToken d = o["days"];
                w.Days = ParseDays(d == null ? null : d.Type == JTokenType.Array ? string.Join(",", ((JArray)d).ToObject<string[]>()) : (string)d);
                w.Start = ParseClock(StrArg(o, "start"), "start"); w.End = ParseClock(StrArg(o, "end"), "end"); w.Label = StrArg(o, "label");
                ws.Add(w);
            }
        }
        else
        {
            var w = new MwWindow();
            JToken d = a["days"];
            w.Days = ParseDays(d == null ? null : d.Type == JTokenType.Array ? string.Join(",", ((JArray)d).ToObject<string[]>()) : (string)d);
            w.Start = ParseClock(StrArg(a, "start"), "start"); w.End = ParseClock(StrArg(a, "end"), "end");
            ws.Add(w);
        }
        if (ws.Count == 0 || ws.Count > MaxWindows) throw new Exception("1-" + MaxWindows + " Fenster je Wartungsprofil.");
        foreach (MwWindow w in ws) if (w.End <= w.Start) throw new Exception("Fenster " + WindowText(w) + ": Ende muss nach dem Beginn liegen (ueber Mitternacht: zwei Fenster).");
        return ws;
    }

