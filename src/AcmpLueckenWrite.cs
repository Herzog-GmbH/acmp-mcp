            while (r.Read()) { parts.Add(Str(r, 0) ?? "?"); if (!r.IsDBNull(1) && Convert.ToInt32(r.GetValue(1), CultureInfo.InvariantCulture) == 0) aagon = true; }
        path = string.Join("\\", parts.ToArray());
    }

