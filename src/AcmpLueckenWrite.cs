        return plan;
    }

    JObject ExecRestoreState(JObject plan, string requester)
    {
        string name = (string)plan["backup"];
        JObject b = JObject.Parse(File.ReadAllText(Path.Combine(_backupDir, name)));
        JArray before = (JArray)b["before"], after = (JArray)b["after"], specs = (JArray)b["specs"];
        int nIns = 0, nDel = 0, nUpd = 0;
        using (var wc = new SqlConnection(_writeCs))
        {
            wc.Open();
            try
            {
            using (SqlTransaction tx = wc.BeginTransaction(IsolationLevel.Serializable))
            {
                for (int i = 0; i < specs.Count; i++)
                {
                    if (IsBackupOnly(specs[i])) continue;
                    string drift = Drift(Snap(wc, tx, (JObject)specs[i]), (JObject)after[i]);
                    if (drift != null) throw new Exception("Seit der Sicherung geaendert (" + drift + ") - zurueckgerollt, nichts geaendert.");
                }
                // 1. entfernen (Kinder zuerst; Zeilen, die eine Kaskade oder ein Trigger schon entfernt hat, ueberspringen)
                for (int i = specs.Count - 1; i >= 0; i--)
                {
                    if (IsBackupOnly(specs[i])) continue;
                    JObject bs = (JObject)before[i], as_ = (JObject)after[i];
                    Dictionary<string, JObject> bk = RowsByKey(bs);
                    foreach (JObject row in (JArray)as_["rows"])
                    {
                        if (bk.ContainsKey(KeyOf(row, (JArray)as_["k"]))) continue;
                        if (RowExists(wc, tx, as_, row)) { RowCmd(wc, tx, "DELETE FROM", as_, row, null).ExecuteNonQuery(); nDel++; }
                    }
                }
                // 2. wieder anlegen (Eltern zuerst)
                var reJobs = new List<string>();
                for (int i = 0; i < specs.Count; i++)
                {
                    if (IsBackupOnly(specs[i])) continue;
                    JObject bs = (JObject)before[i], as_ = (JObject)after[i];
                    Dictionary<string, JObject> ak = RowsByKey(as_);
                    foreach (JObject row in (JArray)bs["rows"])
                        if (!ak.ContainsKey(KeyOf(row, (JArray)bs["k"])) && !RowExists(wc, tx, bs, row))
                        {
                            InsertSnapRow(wc, tx, bs, row); nIns++;
                            if ((string)bs["t"] == "SYS_Jobs" && row["Id"] != null) reJobs.Add((string)row["Id"]);
                        }
                }
                // 2b. Job-Monitor wiederhergestellter Jobs: Status wie vorher (TG_Delete_SYS_Templates_Jobs hatte ihn auf 2 gesetzt)
                for (int i = 0; i < specs.Count; i++)
                {
                    if ((string)specs[i]["t"] != "SYS_Jobs_Logs" || reJobs.Count == 0) continue;
                    foreach (JObject row in (JArray)((JObject)before[i])["rows"])
                    {
                        if (row["JobId"] == null || row["State"] == null || row["State"].Type == JTokenType.Null || !reJobs.Exists(x => string.Equals(x, (string)row["JobId"], StringComparison.OrdinalIgnoreCase))) continue;
                        var lq = wc.CreateCommand(); lq.Transaction = tx; lq.CommandTimeout = SqlTimeout;
                        lq.CommandText = "UPDATE SYS_Jobs_Logs SET State = @s WHERE JobId = @j";
                        lq.Parameters.Add(ParFor("@s", "tinyint", row["State"])); lq.Parameters.Add(ParFor("@j", "uniqueidentifier", row["JobId"]));
                        lq.ExecuteNonQuery();
                    }
                }
                // 3. geaenderte Spalten zuruecksetzen
                for (int i = 0; i < specs.Count; i++)
                {
                    if (IsBackupOnly(specs[i])) continue;
                    JObject bs = (JObject)before[i], as_ = (JObject)after[i];
                    Dictionary<string, JObject> ak = RowsByKey(as_);
                    foreach (JObject row in (JArray)bs["rows"])
                    {
                        JObject now;
                        if (!ak.TryGetValue(KeyOf(row, (JArray)bs["k"]), out now) || Canon(now) == Canon(row)) continue;
                        RowCmd(wc, tx, "UPDATE", bs, row, now).ExecuteNonQuery(); nUpd++;
                    }
                }
                for (int i = 0; i < specs.Count; i++)
                {
                    if (IsBackupOnly(specs[i])) continue;
                    string drift = Drift(Snap(wc, tx, (JObject)specs[i]), (JObject)before[i]);
                    if (drift != null) throw new Exception("Nach der Ruecknahme stimmt der Stand nicht mit der Sicherung ueberein (" + drift + ") - zurueckgerollt, nichts geaendert.");
                }
                tx.Commit();
            }
            }
            catch (SqlException ex)
            {
                if (ex.Number != 547) throw;
                // Fremdschluessel: z.B. Zuordnung zu einem inzwischen geloeschten Wartungsprofil - die Drift-Pruefung sieht nur die gesicherten Zeilen (Praxistest 25.10.2026)
                throw new Exception("Die Sicherung passt nicht mehr: ein Objekt, auf das sie verweist, fehlt inzwischen oder wird noch gebraucht (" + ex.Message.Split('\n')[0].Trim() +
                                    ") - zurueckgerollt, nichts geaendert. Erst die spaetere Aenderung zuruecknehmen.");
            }
        }
        _log("acmp_job_restore (zustand, " + b["tool"] + ") von " + requester + ": " + b["name"] + ", Sicherung " + name);
        var res = new JObject();
        res["ok"] = true; res["aktion"] = "Stand vor '" + b["tool"] + "' wiederhergestellt: " + b["name"];
        res["zeilen"] = nIns + " wieder angelegt, " + nDel + " entfernt, " + nUpd + " zurueckgesetzt";
        res["sicherung"] = name;
        return res;
    }

    static string WhereKey(JObject snap, JObject row, SqlCommand q, string prefix)
    {
        var w = new List<string>(); int i = 0;
        JObject types = (JObject)snap["types"];
        foreach (JToken k in (JArray)snap["k"])
        {
            string col = (string)k, pn = "@" + prefix + (i++);
            JToken v = row[col];
            if (v == null || v.Type == JTokenType.Null) w.Add("[" + col + "] IS NULL");
            else { w.Add("[" + col + "] = " + pn); q.Parameters.Add(ParFor(pn, (string)types[col], v)); }
        }
        return string.Join(" AND ", w.ToArray());
    }

    static bool RowExists(SqlConnection c, SqlTransaction tx, JObject snap, JObject row)
    {
        var q = c.CreateCommand(); q.Transaction = tx; q.CommandTimeout = SqlTimeout;
        q.CommandText = "SELECT COUNT(*) FROM dbo.[" + (string)snap["t"] + "] WHERE " + WhereKey(snap, row, q, "k");
        return Convert.ToInt32(q.ExecuteScalar(), CultureInfo.InvariantCulture) > 0;
    }

    // DELETE (row = Schluessel) bzw. UPDATE der Spalten, die sich zwischen now und row unterscheiden
    static SqlCommand RowCmd(SqlConnection c, SqlTransaction tx, string verb, JObject snap, JObject row, JObject now)
    {
        string t = (string)snap["t"];
        if (Array.IndexOf(LwTables, t) < 0) throw new Exception("Tabelle " + t + " ist fuer die Ruecknahme nicht vorgesehen.");
        var q = c.CreateCommand(); q.Transaction = tx; q.CommandTimeout = SqlTimeout;
        if (verb == "DELETE FROM") { q.CommandText = "DELETE FROM dbo.[" + t + "] WHERE " + WhereKey(snap, row, q, "k"); return q; }
        var set = new List<string>(); int i = 0; JObject types = (JObject)snap["types"];
        foreach (var kv in row)
        {
            JToken n = now[kv.Key];
            if (n != null && n.ToString(Newtonsoft.Json.Formatting.None) == kv.Value.ToString(Newtonsoft.Json.Formatting.None)) continue;
            string pn = "@s" + (i++);
            set.Add("[" + kv.Key + "] = " + pn); q.Parameters.Add(ParFor(pn, (string)types[kv.Key], kv.Value));
        }
        q.CommandText = "UPDATE dbo.[" + t + "] SET " + string.Join(", ", set.ToArray()) + " WHERE " + WhereKey(snap, row, q, "k");
        return q;
    }

    static void InsertSnapRow(SqlConnection c, SqlTransaction tx, JObject snap, JObject row)
    {
        string t = (string)snap["t"];
        if (Array.IndexOf(LwTables, t) < 0) throw new Exception("Tabelle " + t + " ist fuer die Ruecknahme nicht vorgesehen.");
        var q = c.CreateCommand(); q.Transaction = tx; q.CommandTimeout = SqlTimeout;
        var cols = new List<string>(); var vals = new List<string>(); int i = 0; JObject types = (JObject)snap["types"];
        foreach (var kv in row)
        {
            string ty = (string)types[kv.Key];
            if (ty == "timestamp" || ty == "rowversion") continue;
            string pn = "@v" + (i++);
            cols.Add("[" + kv.Key + "]"); vals.Add(pn); q.Parameters.Add(ParFor(pn, ty, kv.Value));
        }
