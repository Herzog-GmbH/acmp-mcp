                if (drift != null) throw new Exception("Seit der Sicherung geaendert (" + drift + ") - nichts geplant. Bitte in der Console pruefen.");
                int ins, del, upd; DiffCounts((JObject)before[i], (JObject)after[i], out ins, out del, out upd);
                var l = new List<string>();
