    public static List<string> ParseDays(string s)
    {
        var set = new HashSet<string>();
        if (s == null) throw new Exception("days fehlt (z.B. \"MO,DI,MI,DO,FR\", \"werktags\", \"taeglich\" oder \"SA\").");
        foreach (string raw in s.Split(',', ';', ' ', '/'))
        {
            string d = raw.Trim().ToLowerInvariant().Replace("ä", "ae");
            if (d.Length == 0) continue;
            switch (d)
            {
                case "mo": case "mon": case "montag": case "monday": set.Add("MO"); break;
                case "di": case "tu": case "tue": case "dienstag": case "tuesday": set.Add("TU"); break;
                case "mi": case "we": case "wed": case "mittwoch": case "wednesday": set.Add("WE"); break;
                case "do": case "th": case "thu": case "donnerstag": case "thursday": set.Add("TH"); break;
                case "fr": case "fri": case "freitag": case "friday": set.Add("FR"); break;
                case "sa": case "sat": case "samstag": case "saturday": set.Add("SA"); break;
                case "so": case "su": case "sun": case "sonntag": case "sunday": set.Add("SU"); break;
                case "werktags": case "weekdays": case "mo-fr": foreach (string x in new[] { "MO", "TU", "WE", "TH", "FR" }) set.Add(x); break;
                case "taeglich": case "daily": case "alle": case "jedentag": case "mo-so": foreach (string x in DayCodes) set.Add(x); break;
                default: throw new Exception("Tag '" + raw.Trim() + "' unbekannt (MO DI MI DO FR SA SO, werktags, taeglich).");
            }
        }
        if (set.Count == 0) throw new Exception("days ist leer.");
        var l = new List<string>(); foreach (string x in DayCodes) if (set.Contains(x)) l.Add(x);
        return l;
    }

    // "HH:MM" -> Minuten seit Mitternacht
    public static int ParseClock(string s, string what)
    {
        if (s == null) throw new Exception(what + " fehlt (HH:MM).");
        string[] p = s.Trim().Split(':');
        int h, m;
        if (p.Length != 2 || !int.TryParse(p[0], NumberStyles.None, CultureInfo.InvariantCulture, out h) || !int.TryParse(p[1], NumberStyles.None, CultureInfo.InvariantCulture, out m) ||
            h < 0 || h > 23 || m < 0 || m > 59) throw new Exception(what + " '" + s + "' ist keine Uhrzeit HH:MM (00:00-23:59).");
        return h * 60 + m;
    }

    static string Clock(int min) { return (min / 60).ToString("00") + ":" + (min % 60).ToString("00"); }

    public static string WindowText(MwWindow w)
    {
        var d = new List<string>(); foreach (string x in w.Days) d.Add(DayNamesDe[Array.IndexOf(DayCodes, x)]);
        string days = w.Days.Count == 7 ? "taeglich" : w.Days.Count == 5 && !w.Days.Contains("SA") && !w.Days.Contains("SU") ? "werktags (Mo-Fr)" : string.Join(", ", d.ToArray());
        return days + " " + Clock(w.Start) + "-" + Clock(w.End) + (string.IsNullOrEmpty(w.Label) ? "" : " (" + w.Label + ")");
    }

    static string IcalText(string s)
    {
        return (s ?? "").Replace("\\", "\\\\").Replace(";", "\\;").Replace(",", "\\,").Replace("\r", " ").Replace("\n", " ");
    }

    // TimeFrameDefinition wie die Console: je Fenster ein VEVENT, DTSTART am ersten passenden Tag ab heute, RRULE woechentlich an den Tagen
    public static string IcalFor(List<MwWindow> ws, string name, DateTime todayLocal, DateTime nowUtc, Func<string> uid)
    {
        var sb = new StringBuilder();
        Action<string> L = x => sb.Append(x).Append("\r\n");
        L("BEGIN:VCALENDAR"); L("VERSION:2.0"); L("PRODID:-//Aagon GmbH//Aagon Client Management Platform//EN");
        foreach (MwWindow w in ws)
        {
            if (w.End <= w.Start) throw new Exception("Fenster " + WindowText(w) + ": Ende muss nach dem Beginn liegen (ueber Mitternacht: zwei Fenster, z.B. 22:00-23:59 und 00:00-02:00).");
            DateTime d = todayLocal.Date;
            for (int i = 0; i < 7; i++)
            {
                int idx = ((int)d.DayOfWeek + 6) % 7;   // Montag = 0
                if (w.Days.Contains(DayCodes[idx])) break;
                d = d.AddDays(1);
            }
            string day = d.ToString("yyyyMMdd", CultureInfo.InvariantCulture);
            L("BEGIN:VEVENT");
            L("DTSTAMP:" + nowUtc.ToString("yyyyMMdd'T'HHmmss'Z'", CultureInfo.InvariantCulture));
            L("DTSTART:" + day + "T" + (w.Start / 60).ToString("00") + (w.Start % 60).ToString("00") + "00");
            L("DTEND:" + day + "T" + (w.End / 60).ToString("00") + (w.End % 60).ToString("00") + "00");
            L("SUMMARY;LANGUAGE=de-DE:" + IcalText(string.IsNullOrEmpty(w.Label) ? name : w.Label));
            L("X-MICROSOFT-CDO-BUSYSTATUS:BUSY");
            L("UID:" + uid());
            L("RRULE:FREQ=WEEKLY;BYDAY=" + string.Join(",", w.Days.ToArray()));
            L("X-DEVEXPRESS-LABEL:536870912");
            L("STATUS:CONFIRMED");
            L("SEQUENCE:1");
            L("END:VEVENT");
        }
        L("END:VCALENDAR");
        return sb.ToString();
    }

    // Fenster eines vorhandenen Profils lesbar (BYDAY, DTSTART/DTEND-Uhrzeit, SUMMARY)
    public static List<string> IcalWindows(string ical)
    {
        var res = new List<string>();
        if (string.IsNullOrEmpty(ical)) return res;
        string start = null, end = null, days = null, sum = null;
        foreach (string raw in ical.Replace("\r\n", "\n").Split('\n'))
        {
            string l = raw.Trim();
            if (l == "BEGIN:VEVENT") { start = end = days = sum = null; }
            else if (l.StartsWith("DTSTART:") && l.Length >= 21) start = l.Substring(17, 2) + ":" + l.Substring(19, 2);
            else if (l.StartsWith("DTEND:") && l.Length >= 19) end = l.Substring(15, 2) + ":" + l.Substring(17, 2);
            else if (l.StartsWith("RRULE:")) { int i = l.IndexOf("BYDAY="); days = i >= 0 ? l.Substring(i + 6).Split(';')[0] : l.Substring(6); }
            else if (l.StartsWith("SUMMARY")) { int i = l.IndexOf(':'); sum = i >= 0 ? l.Substring(i + 1) : null; }
            else if (l == "END:VEVENT") res.Add((days ?? "einmalig") + " " + (start ?? "?") + "-" + (end ?? "?") + (sum != null ? " (" + sum + ")" : ""));
        }
        return res;
    }

